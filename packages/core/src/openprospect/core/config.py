"""Where things live, secrets from .env, and settings from config/settings.yaml.

Everything is resolved relative to the *workspace*: the folder you run `openprospect` from,
or the folder in the OPENPROSPECT_HOME environment variable. A fresh clone of the repo is a
ready workspace; `openprospect init` fills in .env and config/ from the examples."""

from __future__ import annotations

import os
import re
import secrets
import shutil
import string
from pathlib import Path

import yaml


class Paths:
    """Computed on every access so tests (and OPENPROSPECT_HOME) can point elsewhere."""

    @property
    def home(self) -> Path:
        return Path(os.environ.get("OPENPROSPECT_HOME") or Path.cwd()).resolve()

    @property
    def data(self) -> Path:
        return self.home / "data"

    @property
    def env_file(self) -> Path:
        return self.home / ".env"

    @property
    def config(self) -> Path:
        return self.home / "config"

    @property
    def settings_file(self) -> Path:
        return self.config / "settings.yaml"

    @property
    def queries_file(self) -> Path:
        return self.config / "queries.txt"

    @property
    def profile_file(self) -> Path:
        return self.config / "profile.md"

    @property
    def templates(self) -> Path:
        return self.home / "templates"

    @property
    def prompts(self) -> Path:
        return self.home / "prompts"

    @property
    def infra(self) -> Path:
        return self.home / "infra"


paths = Paths()

