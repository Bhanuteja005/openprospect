GENERATED_SECRETS = [
    "TWENTY_DB_PASSWORD",
    "TWENTY_ENCRYPTION_KEY",
    "LISTMONK_DB_PASSWORD",
    "LISTMONK_ADMIN_PASSWORD",
    "HUGINN_PASSWORD",
    "HUGINN_FEED_SECRET",
]

# config/<name> is created from config/<example> on `init`; the copies hold your own details
# and are git-ignored.
CONFIG_EXAMPLES = {
    "settings.yaml": "settings.example.yaml",
    "queries.txt": "queries.example.txt",
    "profile.md": "profile.example.md",
}


def _rand(n: int = 32) -> str:
    alphabet = string.ascii_letters + string.digits
    return "".join(secrets.choice(alphabet) for _ in range(n))


def read_env_file() -> dict[str, str]:
    values: dict[str, str] = {}
    if paths.env_file.exists():
        for line in paths.env_file.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            k, v = line.split("=", 1)
            values[k.strip()] = v.strip().strip('"').strip("'")
    return values


def write_env_value(key: str, value: str) -> None:
    """Set one KEY=value in .env, keeping everything else."""
    f = paths.env_file
    lines = f.read_text(encoding="utf-8").splitlines() if f.exists() else []
    done = False
    for i, line in enumerate(lines):
        if line.split("=", 1)[0].strip() == key:
            lines[i] = f"{key}={value}"
            done = True
    if not done:
        lines.append(f"{key}={value}")
    f.write_text("\n".join(lines) + "\n", encoding="utf-8")


def init_workspace() -> list[str]:
    """Create .env with random secrets and config/ files from the examples.
    Never overwrites anything. Returns what was added."""
    added = []
    for target, example in CONFIG_EXAMPLES.items():
        dst, src = paths.config / target, paths.config / example
        if not dst.exists() and src.exists():
            shutil.copyfile(src, dst)
            added.append(f"config/{target}")
    current = read_env_file()
    for key in GENERATED_SECRETS:
        if not current.get(key):
            write_env_value(key, _rand())
            added.append(key)
    for key in ("LISTMONK_ADMIN_USER", "HUGINN_USERNAME"):
        if not current.get(key):
            write_env_value(key, "admin")
            added.append(key)
    for key, default in ENV_DEFAULTS.items():
        if key not in current:
            write_env_value(key, default)
            added.append(key)
    return added


def env(key: str) -> str:
    """A real environment variable wins over .env, which wins over the built-in default."""
    val = os.environ.get(key)
    if val:
        return val
    return read_env_file().get(key, ENV_DEFAULTS.get(key, ""))


_settings_cache: dict | None = None


def settings() -> dict:
    global _settings_cache
    if _settings_cache is None:
        f = paths.settings_file
        if not f.exists():
            raise FileNotFoundError(f"{f} not found. Run `openprospect init` first.")
        _settings_cache = yaml.safe_load(f.read_text(encoding="utf-8")) or {}
    return _settings_cache


def reload_settings() -> None:
    global _settings_cache
    _settings_cache = None


def set_huginn_feed_url(url: str) -> None:
    """Write the Huginn feed URL into settings.yaml, keeping the file's comments."""
    f = paths.settings_file
    text = f.read_text(encoding="utf-8")
    text = re.sub(r'huginn_feed_url:\s*".*?"', f'huginn_feed_url: "{url}"', text)
    f.write_text(text, encoding="utf-8")
    reload_settings()
